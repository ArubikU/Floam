package dev.arubiku.floamy3d.runtime.cosmetics;

/**
 * Kinds of Floamy3D cosmetics. CAPE/WINGS/EARS/PART_OVERRIDE ride on the player skin (marker
 * pixel + CEM geometry); ARMOR rides on the equipment/leather-armor path.
 */
public enum CosmeticType {
    CAPE,
    WINGS,
    EARS,
    PLAYER_PART_OVERRIDE,
    ARMOR
}
